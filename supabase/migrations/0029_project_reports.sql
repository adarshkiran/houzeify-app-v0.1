-- Project AI report snapshots (docs/superpowers/specs/2026-10-15-project-ai-report-design.md,
-- section 3). The report itself is computed client-side by the domain's
-- analyzeProject from data the person can already read; this table stores a
-- report a person approved, as an immutable snapshot, so approvedBy/approvedAt
-- (the build plan's AI governance fields) have a durable record.

create table project_reports (
  id uuid primary key default gen_random_uuid(),
  project_id uuid not null references projects (id) on delete cascade,
  as_of date not null,
  status text not null,
  engine text not null,
  payload jsonb not null,
  generated_at timestamptz not null,
  approved_by uuid not null references people (id) on delete restrict,
  approved_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint project_reports_status_check
    check (status in ('on-track', 'at-risk', 'behind', 'not-enough-data'))
);

create index project_reports_project_approved_idx on project_reports (project_id, approved_at desc);

-- Snapshots are never edited. Deleting is refused too, except as the cascade of
-- the project itself being deleted (by then the parent row is already gone).
create or replace function public.project_reports_immutable()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'DELETE' and not exists (select 1 from projects p where p.id = old.project_id) then
    return old;
  end if;
  raise exception 'project reports are immutable; approve a new report instead';
end;
$$;

create trigger project_reports_immutable_guard
  before update or delete on project_reports
  for each row execute function public.project_reports_immutable();

alter table project_reports enable row level security;

-- Reports include internal issues and delay analysis: project managers only, and
-- only whole-project scope (the same bar as approving one).
create policy project_reports_select_manager on project_reports
  for select using (
    public.is_staff(project_id)
    and public.has_permission(project_id, 'project.manage')
    and public.in_scope(project_id, null, null, null)
  );

-- approve_project_report: stores the report the person reviewed as an approved
-- snapshot. The analysis is computed in the domain (src/domain/projectAnalysis.ts)
-- from rows the caller can already read, so the function validates what it can
-- see (project, permission, shape, engine) and stamps who approved and when
-- server-side; it does not recompute the analysis.
create or replace function public.approve_project_report(project_id uuid, payload jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  caller uuid := public.current_person_id();
  report_status text;
  report_as_of date;
  report_generated timestamptz;
  stored projects%rowtype;
  result_row project_reports%rowtype;
begin
  if caller is null
     or not (
       public.has_permission(approve_project_report.project_id, 'project.manage')
       and public.in_scope(approve_project_report.project_id, null, null, null)
     ) then
    raise exception 'permission:Missing permission "project.manage" on project %', approve_project_report.project_id;
  end if;

  select p.* into stored from projects p where p.id = approve_project_report.project_id;
  if not found then
    raise exception 'conflict:That project no longer exists.';
  end if;

  if jsonb_typeof(approve_project_report.payload) is distinct from 'object'
     or length(approve_project_report.payload::text) > 200000 then
    raise exception 'conflict:That report could not be saved.';
  end if;
  if approve_project_report.payload->>'projectId' is distinct from approve_project_report.project_id::text then
    raise exception 'conflict:That report belongs to a different project.';
  end if;
  if approve_project_report.payload->>'source' is distinct from 'ai'
     or approve_project_report.payload->>'createdBy' is distinct from 'ai'
     or approve_project_report.payload->>'engine' is distinct from 'rules-v1' then
    raise exception 'conflict:That report was not generated by Hozie.';
  end if;
  if approve_project_report.payload->>'reviewStatus' is distinct from 'draft' then
    raise exception 'conflict:This report is already approved.';
  end if;

  report_status := approve_project_report.payload->>'status';
  if report_status is null or report_status not in ('on-track', 'at-risk', 'behind', 'not-enough-data') then
    raise exception 'conflict:That report could not be saved.';
  end if;

  begin
    report_as_of := (approve_project_report.payload->>'asOf')::date;
    report_generated := (approve_project_report.payload->>'generatedAt')::timestamptz;
  exception when others then
    raise exception 'conflict:That report could not be saved.';
  end;

  insert into project_reports (project_id, as_of, status, engine, payload, generated_at, approved_by, approved_at)
  values (
    approve_project_report.project_id,
    report_as_of,
    report_status,
    'rules-v1',
    approve_project_report.payload || jsonb_build_object(
      'reviewStatus', 'approved',
      'approvedBy', caller,
      'approvedAt', now()
    ),
    report_generated,
    caller,
    now()
  )
  returning * into result_row;

  return to_jsonb(result_row);
end;
$$;
