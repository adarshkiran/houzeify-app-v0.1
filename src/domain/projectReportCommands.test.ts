import { describe, expect, it } from "vitest"
import { seedConstructionData as seed } from "../mock/seed"
import { ConflictError } from "./errors"
import type { ConstructionDataState } from "./models"
import type { CommandContext } from "./ports"
import { analyzeProject, type ProjectReport } from "./projectAnalysis"
import { approveProjectReport } from "./projectReportCommands"
import { PermissionError, type Session } from "./session"

const manager: Session = { accountType: "business", personId: "person-arjun", organizationId: "org-buildright" }
const homeowner: Session = { accountType: "homeowner", personId: "person-demo-homeowner" }
const NOW = new Date("2026-10-15T09:30:00.000Z")

const ctx = (actor: Session | null): CommandContext => ({
  actor,
  clock: { now: () => NOW },
  ids: { next: (prefix) => `${prefix}-1`, short: () => "s1" },
})

function draft(state: ConstructionDataState = seed, projectId = "project-sharma"): ProjectReport {
  return analyzeProject(state, projectId, "2026-10-15", NOW.toISOString())!
}

describe("approveProjectReport", () => {
  it("stores the report the person reviewed, stamped with who approved and when", () => {
    const report = draft()
    const { state, result } = approveProjectReport(report)(seed, ctx(manager))
    expect(result).toMatchObject({
      id: "project-report-1",
      projectId: "project-sharma",
      asOf: "2026-10-15",
      status: report.status,
      approvedBy: "person-arjun",
      approvedAt: NOW.toISOString(),
    })
    expect(result.report).toEqual({
      ...report,
      reviewStatus: "approved",
      approvedBy: "person-arjun",
      approvedAt: NOW.toISOString(),
    })
    expect(state.projectReports).toEqual([result])
  })

  it("keeps earlier snapshots and does not touch the live data", () => {
    const first = approveProjectReport(draft())(seed, ctx(manager)).state
    const second = approveProjectReport(draft())(first, { ...ctx(manager), ids: { next: () => "project-report-2", short: () => "s" } })
    expect(second.state.projectReports.map((r) => r.id)).toEqual(["project-report-1", "project-report-2"])
    expect(second.state.tasks).toBe(seed.tasks)
  })

  it("refuses a homeowner and a signed-out actor", () => {
    expect(() => approveProjectReport(draft())(seed, ctx(homeowner))).toThrow(PermissionError)
    expect(() => approveProjectReport(draft())(seed, ctx(null))).toThrow(PermissionError)
  })

  it("refuses a member without project.manage", () => {
    const reader: Session = { accountType: "business", personId: "person-reader", organizationId: "org-buildright" }
    const state: ConstructionDataState = {
      ...seed,
      memberships: [
        ...seed.memberships,
        {
          id: "m-reader",
          projectId: "project-sharma",
          principalType: "person",
          principalId: "person-reader",
          role: "supervisor",
          scope: { projectUnitIds: [], stageIds: [], tradeIds: [] },
          permissions: ["project.read"],
          status: "active",
        },
      ],
    }
    expect(() => approveProjectReport(draft())(state, ctx(reader))).toThrow(PermissionError)
  })

  it("refuses a manager of a different project", () => {
    const report = { ...draft(), projectId: "project-reddy" }
    const other: Session = { accountType: "business", personId: "person-someone", organizationId: "org-x" }
    expect(() => approveProjectReport(report)(seed, ctx(other))).toThrow(PermissionError)
  })

  it("refuses an unknown project", () => {
    const report = { ...draft(), projectId: "no-such-project" }
    expect(() => approveProjectReport(report)(seed, ctx(manager))).toThrow()
  })

  it("refuses a report that is already approved or not from the rules engine", () => {
    expect(() =>
      approveProjectReport({ ...draft(), reviewStatus: "approved" })(seed, ctx(manager)),
    ).toThrow(new ConflictError("This report is already approved."))
    expect(() =>
      approveProjectReport({ ...draft(), engine: "llm-x" as "rules-v1" })(seed, ctx(manager)),
    ).toThrow(new ConflictError("That report was not generated by Hozie."))
  })
})
