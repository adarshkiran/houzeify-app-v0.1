import { ConflictError } from "./errors"
import type { EntityId, SavedProjectReport } from "./models"
import { Permissions } from "./permissions"
import type { Command, CommandContext } from "./ports"
import type { ProjectReport } from "./projectAnalysis"
import { authorizingMembership, PermissionError } from "./session"

const iso = (ctx: CommandContext) => ctx.clock.now().toISOString()

/**
 * Approves a Project AI report as the person reviewed it and stores it as an
 * immutable snapshot (build plan §10 AI governance: reviewStatus, approvedBy,
 * approvedAt). Whole-project `project.manage` only, like the report screen.
 * The report is the one the person saw, not a recomputation at click time.
 */
export const approveProjectReport =
  (report: ProjectReport): Command<SavedProjectReport> =>
  (state, ctx) => {
    const membership = authorizingMembership(
      ctx.actor,
      state.memberships,
      state.projectUnits,
      report.projectId,
      [Permissions.PROJECT_MANAGE],
      {},
    )
    if (!membership || !ctx.actor) {
      throw new PermissionError(Permissions.PROJECT_MANAGE, report.projectId)
    }
    if (!state.projects.some((project) => project.id === report.projectId)) {
      throw new ConflictError("That project no longer exists.")
    }
    if (report.source !== "ai" || report.createdBy !== "ai" || report.engine !== "rules-v1") {
      throw new ConflictError("That report was not generated by Hozie.")
    }
    if (report.reviewStatus !== "draft") {
      throw new ConflictError("This report is already approved.")
    }

    const approvedAt = iso(ctx)
    const approvedBy: EntityId = ctx.actor.personId
    const saved: SavedProjectReport = {
      id: ctx.ids.next("project-report"),
      projectId: report.projectId,
      asOf: report.asOf,
      status: report.status,
      report: { ...report, reviewStatus: "approved", approvedBy, approvedAt },
      approvedBy,
      approvedAt,
      createdAt: approvedAt,
    }
    return {
      state: { ...state, projectReports: [...state.projectReports, saved] },
      result: saved,
    }
  }
